def load_json(path: str) -> Dict:
    if not os.path.exists(path): return {}
    try:
        with open(path, 'r', encoding='utf-8') as f:
            return json.load(f)
    except Exception as e:
        print(f"[ERR] Failed to load {path}: {e}")
        return {}

def load_captions_map(video_id: str, captions_root: str) -> Dict[str, str]:
    """
    Locates and loads the caption JSON for the video.
    Returns a dict: { "frame_XXXX": "caption text", ... }
    """
    # Structure seems to be: captions_root / <video_id> / <video_id>_captions_integrated.json
    # Or just flat? User showed: captions_integrated / frames_embodied_captions_integrated / <video_id> / <video_id>_captions_integrated.json
    
    vid_dir = os.path.join(captions_root, video_id)
    if not os.path.isdir(vid_dir):
        # Fallback: maybe just in root?
        vid_dir = captions_root
        
    # Search for json
    cand_path = os.path.join(vid_dir, f"{video_id}_captions_integrated.json")
    if not os.path.exists(cand_path):
        # Look for any json in vid_dir?
        if os.path.exists(vid_dir):
            for f in os.listdir(vid_dir):
                if f.endswith('.json') and video_id in f:
                    cand_path = os.path.join(vid_dir, f)
                    break
    
    if not os.path.exists(cand_path):
        print(f"[WARN] No captions found for {video_id} at {cand_path}")
        return {}
        
    data = load_json(cand_path)
    frame_map = {}
    for item in data.get('frames', []):
        fid = item.get('frame_id')
        cap = item.get('caption')
        if fid and cap:
            frame_map[fid] = cap
            
    return frame_map

def parse_comments_docx(docx_path: str) -> Dict[str, List[Dict[str, str]]]:
    """Parses DOCX comments (reused from correlate_sections)."""
    if not Document: return {}
    doc = Document(docx_path)
    by_video = {}
    from collections import defaultdict
    by_video = defaultdict(list)
    
    cur_vid = None
    buffer = []

    def get_vid(text):
        if "youtu" not in text: return None
        m = re.search(r"v=([A-Za-z0-9_-]{11})", text)
        if m: return m.group(1)
        m = re.search(r"youtu\.be/([A-Za-z0-9_-]{11})", text)
        if m: return m.group(1)
        return None

    def flush():
        nonlocal buffer
        if cur_vid and buffer:
            joined = " ".join(buffer).strip()
            if joined:
                by_video[cur_vid].append({'comment': joined})
        buffer = []

    for para in doc.paragraphs:
        t = para.text.strip()
        vid = get_vid(t)
        if vid:
            flush()
            cur_vid = vid
        elif t:
            buffer.append(t)
    flush()
    return dict(by_video)

def load_comments(comments_input: str, video_id: str, preloaded_docx: Optional[Dict] = None) -> List[Dict[str, str]]:
    """Loads comments for a video from JSON dir or preloaded DOCX."""
    if preloaded_docx:
        return preloaded_docx.get(video_id, [])
    
    if os.path.isdir(comments_input):
        cand = os.path.join(comments_input, f"{video_id}.json")
        path = None
        if os.path.exists(cand): path = cand
        else:
            for root, _, files in os.walk(comments_input):
                if f"{video_id}.json" in files:
                    path = os.path.join(root, f"{video_id}.json")
                    break
        
        comments = []
        if path:
            try:
                with open(path, 'r', encoding='utf-8') as f:
                    content = f.read().strip()
                    if not content: return []
                    try:
                        data = json.loads(content)
                        if isinstance(data, list):
                            for c in data:
                                if isinstance(c, dict) and 'text' in c: comments.append({'comment': c['text']})
                                elif isinstance(c, str): comments.append({'comment': c})
                        elif isinstance(data, dict) and 'text' in data:
                             comments.append({'comment': data['text']})
                    except json.JSONDecodeError:
                        for line in content.split('\n'):
                            if not line.strip(): continue
                            try:
                                obj = json.loads(line)
                                if 'text' in obj: comments.append({'comment': obj['text']})
                            except: pass
            except Exception as e:
                print(f"[ERR] Error reading comments {path}: {e}")
        return comments
    return []

# -------------------- Helpers --------------------

def enrich_segments(segments: List[Dict], frame_map: Dict[str, str]):
    """
    Populate 'visual_summary' for each segment by aggregating captions of its frames.
    """
    for seg in segments:
        frames = seg.get('frames', [])
        captions = []
        for f in frames:
            # f might be "frame_0000.jpg" or "frame_0000.png"
            # caption map keys are "frame_0000"
            base = os.path.splitext(f)[0]
            if base in frame_map:
                captions.append(frame_map[base])
        
        # Simple concatenation or summary?
        # User asked for "correlation with comments".
        # Concatenating all frame captions might be too long for context window if specific frame-by-frame.
        # But usually we have ~3 frames per 10s segment. Concatenation is fine.
        seg['visual_summary'] = "\n".join(captions) if captions else "(No visual info)"

# -------------------- Correlation Logic --------------------

def run_llm_batch(context_key: str, context_label: str, segments: List[Dict], comments: List[str], model_name: str) -> List[Dict]:
    """
    Generic correlation function.
    context_key: key in segment dict to use as context (e.g., 'visual_summary' or 'transcript')
    context_label: label for prompt (e.g., "VISUAL DESCRIPTION" or "TRANSCRIPT")
    """
    
    # 1. Build Context String
    # To save tokens, we might only include non-empty contexts
    seg_context_str = ""
    valid_seg_ids = []
    
    for seg in segments:
        content = seg.get(context_key, "").strip()
        if not content or content == "(No visual info)" or content == "(No speech)":
            continue
            
        seg_context_str += f"Segment {seg['segment_index']}:\n{content}\n---\n"
        valid_seg_ids.append(seg['segment_index'])

    if not seg_context_str:
        return [] # No context to match against
    
    # 2. Prepare Batches
    batch_size = 5
    results = []
    
    for i in range(0, len(comments), batch_size):
        batch = comments[i:i+batch_size]
        
        prompt = f"""
        You are matching user comments to specific video segments based on {context_label}.
        
        VIDEO SEGMENTS:
        {seg_context_str}
        
        COMMENTS TO CLASSIFY:
        {json.dumps(batch, indent=2)}
        
        TASK:
        For each comment, determine if it correlates to any of the provided Segments based on the {context_label}.
        Return a correlation score (0-100) and a valid explanation.
        If multiple segments match, pick the strongest one. 
        If no segment matches well, return null or score 0.
        
        OUTPUT FORMAT (Strict JSON list):
        [
          {{"comment": "...", "segment_id": 1, "correlated": true, "score": 90, "explanation": "Refers to object described in visual"}},
          {{"comment": "...", "segment_id": null, "correlated": false, "score": 0, "explanation": "Generic comment"}}
        ]
        """
        
        try:
            stream = generate_response(model_name, prompt)
            resp_text = "".join(stream_parser(stream)).strip()
            
            # Extract JSON
            m = re.search(r'\[.*\]', resp_text, flags=re.DOTALL)
            if m:
                batch_results = json.loads(m.group(0))
                for res in batch_results:
                    if res.get('correlated') and res.get('segment_id') in valid_seg_ids:
                        results.append(res)
        except Exception as e:
            print(f"[ERR] Batch failed ({context_label}): {e}")
            
    return results

def dual_correlate(segments: List[Dict], comments: List[Dict], model_name: str):
    """
    Runs two passes of correlation.
    Mutates segments to add 'visual_matches' and 'transcript_matches'.
    """
    # Prepare unique comments text to avoid duplicate LLM calls if many dupes
    unique_texts = list({c['comment'] for c in comments})
    if len(unique_texts) > 100:
        print(f"[INFO] Sampling 100 comments out of {len(unique_texts)}.")
        unique_texts = unique_texts[:100]

    # PASS 1: Visual
    print("    Running Visual Correlation...")
    visual_results = run_llm_batch('visual_summary', 'VISUAL DESCRIPTION', segments, unique_texts, model_name)
    
    # PASS 2: Transcript
    print("    Running Transcript Correlation...")
    transcript_results = run_llm_batch('transcript', 'TRANSCRIPT content', segments, unique_texts, model_name)
    
    # Assign back to segments
    # Map results by segment_id
    for seg in segments:
        seg['visual_matches'] = []
        seg['transcript_matches'] = []
        
    for res in visual_results:
        sid = res.get('segment_id')
        if sid:
            # Find segment (assuming sorted index 1-N matches list index 0-(N-1))
            # Safest to search
            target = next((s for s in segments if s['segment_index'] == sid), None)
            if target:
                target['visual_matches'].append(res)
                
    for res in transcript_results:
        sid = res.get('segment_id')
        if sid:
            target = next((s for s in segments if s['segment_index'] == sid), None)
            if target:
                target['transcript_matches'].append(res)

