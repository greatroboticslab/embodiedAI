def generate_docx_report(video_id: str, segments: List[Dict], output_path: str):
    if not Document:
        print("[WARN] python-docx not installed. Skipping DOCX.")
        return

    doc = Document()
    doc.add_heading(f"Correlation Analysis: {video_id}", 0)
    
    # Summary Stats
    total_vis = sum(len(s['visual_matches']) for s in segments)
    total_trans = sum(len(s['transcript_matches']) for s in segments)
    
    doc.add_heading("Summary Statistics", 1)
    doc.add_paragraph(f"Total Segments: {len(segments)}")
    doc.add_paragraph(f"Total Visual Correlations: {total_vis}")
    doc.add_paragraph(f"Total Transcript Correlations: {total_trans}")
    
    doc.add_heading("Segment Details", 1)
    
    for seg in segments:
        vis_count = len(seg.get('visual_matches', []))
        trans_count = len(seg.get('transcript_matches', []))
        
        # Only show segments with matches? Or all? 
        # User said "Each section should have two correlation results".
        # Let's show all, but highlight active ones.
        
        h = doc.add_heading(f"Segment {seg['segment_index']} ({int(seg['start_time'])}-{int(seg['end_time'])}s)", 2)
        
        # Context Table
        table = doc.add_table(rows=1, cols=2)
        table.autofit = True
        hdr = table.rows[0].cells
        hdr[0].text = "Transcript Content"
        hdr[1].text = "Visual Summary"
        
        # Content Row
        row = table.add_row().cells
        row[0].text = seg.get('transcript', "").strip() or "(No speech)"
        vis_text = seg.get('visual_summary', "").strip()
        if len(vis_text) > 500: vis_text = vis_text[:500] + "..." # Truncate long captions in table
        row[1].text = vis_text or "(No visuals)"
        
        # Matches
        if vis_count > 0 or trans_count > 0:
            doc.add_heading("Matches", 3)
            
            if vis_count > 0:
                doc.add_paragraph(f"Visual Correlations ({vis_count}):", style='Heading 4')
                for m in seg['visual_matches']:
                    p = doc.add_paragraph(style='List Bullet')
                    p.add_run(f"[{m['score']}%] ").bold = True
                    p.add_run(f"{m['comment']}")
                    p.add_run(f"\nExample: {m['explanation']}").italic = True

            if trans_count > 0:
                doc.add_paragraph(f"Transcript Correlations ({trans_count}):", style='Heading 4')
                for m in seg['transcript_matches']:
                    p = doc.add_paragraph(style='List Bullet')
                    p.add_run(f"[{m['score']}%] ").bold = True
                    p.add_run(f"{m['comment']}")
                    p.add_run(f"\nReason: {m['explanation']}").italic = True
        else:
            doc.add_paragraph("No correlations found.", style='Body Text')
            
        doc.add_paragraph("_" * 40) # Divider

    try:
        doc.save(output_path)
    except Exception as e:
        print(f"[ERR] Failed to save DOCX: {e}")

# -------------------- Main --------------------

def main():
    parser = argparse.ArgumentParser(description="Correlate Segments (Dual Modality)")
    parser.add_argument("--segments_root", required=True, help="Folder with <vid>_manual_sections.json")
    parser.add_argument("--comments_root", required=True, help="Dir (JSON) or File (DOCX)")
    parser.add_argument("--captions_root", required=True, help="Path to CaptionAnalysis/.../integrated_caption")
    parser.add_argument("--output_dir", required=True)
    parser.add_argument("--model", default="llama3")
    
    args = parser.parse_args()
    
    if not os.path.exists(args.output_dir):
        os.makedirs(args.output_dir)

    # Pre-load DOCX if needed
    is_docx = False
    preloaded = {}
    if args.comments_root.lower().endswith('.docx'):
        print(f"[INFO] Parsing Comments DOCX: {args.comments_root}")
        preloaded = parse_comments_docx(args.comments_root)
        is_docx = True
        
    # Find segment files
    seg_files = [f for f in os.listdir(args.segments_root) if f.endswith('_manual_sections.json')]
    print(f"[INFO] Found {len(seg_files)} segment files.")
    
    for f in seg_files:
        # File name format: <vid>_manual_sections.json
        vid = f.replace('_manual_sections.json', '')
        print(f"\nProcessing {vid}...")
        
        # 1. Load Segments
        seg_path = os.path.join(args.segments_root, f)
        seg_data = load_json(seg_path)
        if not seg_data: continue
        segments = seg_data.get('segments', [])
        
        if not segments:
            print("  No segments found in file.")
            continue
            
        # 2. Load Captions
        print("  Loading captions...")
        frame_map = load_captions_map(vid, args.captions_root)
        enrich_segments(segments, frame_map)
        
        # 3. Load Comments
        comments = load_comments(args.comments_root, vid, preloaded)
        if not comments:
            print("  No comments found.")
            # We can still produce output with 0 matches if desired, or skip.
            # Let's proceed to show metadata at least.
        
        # 4. Correlate
        if comments:
            print(f"  Correlating {len(comments)} comments against {len(segments)} segments...")
            dual_correlate(segments, comments, args.model)
            
        # 5. Save Outputs
        out_json = os.path.join(args.output_dir, f"{vid}_segment_correlation.json")
        result = {
            "video_id": vid,
            "duration": seg_data.get('duration', 0),
            "segments": segments
        }
        with open(out_json, 'w', encoding='utf-8') as f_out:
            json.dump(result, f_out, indent=2)
            
        out_docx = os.path.join(args.output_dir, f"{vid}_segment_correlation.docx")
        generate_docx_report(vid, segments, out_docx)
        
        print(f"  > Saved to {args.output_dir}")

if __name__ == "__main__":
    main()
