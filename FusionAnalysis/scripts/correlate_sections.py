def load_sections(sections_path: str) -> Dict:
    """Load the sections JSON file for a video."""
    if not os.path.exists(sections_path):
        return {}
    try:
        with open(sections_path, 'r', encoding='utf-8') as f:
            return json.load(f)
    except Exception as e:
        print(f"[ERR] Failed to load sections {sections_path}: {e}")
        return {}

def parse_comments_docx(docx_path: str) -> Dict[str, List[Dict[str, str]]]:
    """Parses DOCX comments."""
    if not Document:
        print("[WARN] python-docx not installed.")
        return {}
    doc = Document(docx_path)
    by_video = {}
    from collections import defaultdict
    by_video = defaultdict(list)
    
    cur_vid = None
    buffer = []

    def get_vid(text):
        if "youtu" not in text: return None
        m = re.search(r"v=([A-Za-z0-9_-]{11,})", text)
        if m: return m.group(1)
        m = re.search(r"youtu\.be/([A-Za-z0-9_-]{11,})", text)
        if m: return m.group(1)
        return None

    def flush():
        nonlocal buffer
        if cur_vid and buffer:
            joined = " ".join(buffer).strip()
            if joined:
                by_video[cur_vid].append({'comment': joined})
        buffer = []

    for para in doc.paragraphs:
        t = para.text.strip()
        vid = get_vid(t)
        if vid:
            flush()
            cur_vid = vid
        elif t:
            buffer.append(t)
    flush()
    return dict(by_video)

def load_comments(comments_input: str, video_id: str, preloaded_docx: Optional[Dict] = None) -> List[Dict[str, str]]:
    if preloaded_docx:
        return preloaded_docx.get(video_id, [])
    
    # Check Directory
    if os.path.isdir(comments_input):
        cand = os.path.join(comments_input, f"{video_id}.json")
        path = None
        if os.path.exists(cand): path = cand
        else:
            for root, _, files in os.walk(comments_input):
                if f"{video_id}.json" in files:
                    path = os.path.join(root, f"{video_id}.json")
                    break
        
        comments = []
        if path:
            try:
                with open(path, 'r', encoding='utf-8') as f:
                    content = f.read().strip()
                    if not content: return []
                    try:
                        data = json.loads(content)
                        if isinstance(data, list):
                            for c in data:
                                if isinstance(c, dict) and 'text' in c: comments.append({'comment': c['text']})
                                elif isinstance(c, str): comments.append({'comment': c})
                        elif isinstance(data, dict) and 'text' in data:
                             comments.append({'comment': data['text']})
                    except json.JSONDecodeError:
                        for line in content.split('\n'):
                            if not line.strip(): continue
                            try:
                                obj = json.loads(line)
                                if 'text' in obj: comments.append({'comment': obj['text']})
                            except: pass
            except Exception as e:
                print(f"[ERR] Error reading comments {path}: {e}")
        return comments
    return []

# -------------------- Correlation Logic --------------------

def correlate_comments(sections: List[Dict], comments: List[Dict], model_name: str):
    """Correlate comments to sections using LLM."""
    profiles = ""
    for sec in sections:
        # Sections structure from JSON: {'id':..., 'title':..., 'summary':...}
        profiles += f"Section {sec.get('id')}: {sec.get('title')}\nSummary: {sec.get('summary')}\nVisuals: {sec.get('visual_cues')}\nKeywords: {sec.get('verbal_cues')}\n---\n"
        
    unique_comments = list({c['comment'] for c in comments})
    if len(unique_comments) > 100:
        print(f"[INFO] Sampling 100 comments out of {len(unique_comments)}.")
        unique_comments = unique_comments[:100]
        
    batch_size = 5
    for i in range(0, len(unique_comments), batch_size):
        batch = unique_comments[i:i+batch_size]
        
        prompt = f"""
        You are matching user comments to specific sections of a video.
        
        VIDEO SECTIONS:
        {profiles}
        
        COMMENTS TO CLASSIFY:
        {json.dumps(batch, indent=2)}
        
        TASK:
        For each comment, identify which Section ID (1, 2, 3...) it correlates to most strongly. 
        If it's generic or doesn't match specific content, use null.
        
        OUTPUT FORMAT (Strict JSON list of objects):
        [
          {{"comment": "...", "section_id": 1, "confidence": 90, "reason": "Mentions visual cue X"}},
          {{"comment": "...", "section_id": null, "confidence": 0, "reason": "Generic praise"}}
        ]
        """
        try:
            stream = generate_response(model_name, prompt)
            resp_text = "".join(stream_parser(stream)).strip()
            m = re.search(r'\[.*\]', resp_text, flags=re.DOTALL)
            if m:
                results = json.loads(m.group(0))
                for res in results:
                    sec_id = res.get('section_id')
                    if sec_id:
                        for sec in sections:
                            if sec.get('id') == sec_id:
                                if 'matched_comments' not in sec: sec['matched_comments'] = []
                                sec['matched_comments'].append(res)
                                break
        except Exception as e:
            print(f"[ERR] Batch failed: {e}")

